"""Safely diagnose HerFirst's AMD task-guidance call without printing API credentials."""
from pathlib import Path
import json
import os
import sys

import httpx
from dotenv import load_dotenv

BACKEND_DIR = Path(__file__).resolve().parent
load_dotenv(BACKEND_DIR / ".env")

API_KEY = os.getenv("AMD_API_KEY", "").strip()
BASE_URL = os.getenv("AMD_BASE_URL", "").strip().rstrip("/")
MODEL_NAME = os.getenv("AMD_MODEL_NAME", "").strip()

print("AMD API key present:", bool(API_KEY))
print("Base URL:", BASE_URL or "(missing)")
print("Model:", MODEL_NAME or "(missing)")
if not all((API_KEY, BASE_URL, MODEL_NAME)):
    print("RESULT: One or more AMD settings are missing from backend/.env")
    sys.exit(1)

req = {
    "task": {
        "id": "task-1",
        "milestone_id": "milestone-1",
        "title": "Create project homepage",
        "description": "Build a simple homepage with a heading and introduction.",
        "why_it_matters": "The homepage introduces the project to users.",
        "step_by_step_tips": [
            "Plan the homepage content",
            "Build the layout",
            "Test the page in the browser",
        ],
        "estimated_minutes": 30,
        "is_completed": False,
    },
    "project": {
        "title": "HerFirst",
        "description": "A beginner-friendly project planning app.",
        "category": "web",
    },
}

system_prompt = (
    "You are a patient mentor for a person who may be opening a code editor for "
    "the first time. Return a valid JSON object with task_id,task_title,summary,"
    "what_to_do_next,why_it_matters,action_steps,common_pitfalls,"
    "beginner_encouragement,realistic_example,expected_result,verification_steps. "
    "Make the guide specific to the supplied task and project description. Start "
    "with a plain-language explanation, then provide numbered, sequential steps. "
    "Explain where to look and how to find existing files using search; never invent "
    "filenames, folder paths, commands, or project structure. Distinguish planning "
    "tasks from coding tasks. For code examples, say which stack they apply to and "
    "whether the code is illustrative or ready to paste. Include the expected result, "
    "a normal test, a relevant edge case, and simple troubleshooting. Keep language "
    "clear, avoid unexplained jargon, and do not claim anything was tested unless it was."
    " Return only a valid JSON object, with no markdown fences."
)

try:
    response = httpx.post(
        f"{BASE_URL}/chat/completions",
        headers={
            "Authorization": f"Bearer {API_KEY}",
            "Content-Type": "application/json",
        },
        json={
            "model": MODEL_NAME,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": json.dumps(req, ensure_ascii=False)},
            ],
            "temperature": 0.3,
            "response_format": {"type": "json_object"},
        },
        timeout=30.0,
    )
    print("HTTP status:", response.status_code)
    if not response.is_success:
        print("AMD error body:", response.text[:1500])
        print("RESULT: AMD rejected this full guidance request. Do not share any API key.")
        sys.exit(2)
    try:
        body = response.json()
        content = body["choices"][0]["message"]["content"]
    except (ValueError, KeyError, IndexError, TypeError) as exc:
        print("RESULT: AMD returned an unexpected response structure.")
        print("Details:", type(exc).__name__, str(exc)[:600])
        print("Body preview:", response.text[:1200])
        sys.exit(3)

    print("Model returned:", body.get("model", "(not reported)"))
    print("Generated content length:", len(str(content)))
    try:
        generated = json.loads(content)
    except (ValueError, TypeError) as exc:
        print("RESULT: The request succeeded, but model content was not valid JSON.")
        print("Details:", type(exc).__name__, str(exc)[:600])
        print("Content preview:", str(content)[:1200])
        sys.exit(4)

    if not isinstance(generated, dict):
        print("RESULT: Model output was valid JSON but was not an object.")
        print("Content preview:", str(content)[:1000])
        sys.exit(5)

    generated.update({
        "task_id": req["task"]["id"],
        "task_title": req["task"]["title"],
        "source": "amd_ai",
        "source_status": f"Generated by configured AMD model {MODEL_NAME}.",
    })
    try:
        # Validate against the exact response schema used by the running backend.
        sys.path.insert(0, str(BACKEND_DIR))
        from app.schemas import GuidanceResponse
        GuidanceResponse.model_validate(generated)
    except Exception as exc:
        print("RESULT: AMD returned JSON, but it does not match HerFirst's GuidanceResponse schema.")
        print("Validation detail:", str(exc)[:1800])
        print("Returned JSON keys:", ", ".join(sorted(generated.keys())))
        sys.exit(6)

    print("RESULT: Full AMD guidance response passes JSON parsing and HerFirst schema validation.")
    print("source would be: amd_ai")
    print("summary preview:", str(generated.get("summary", ""))[:250])
except httpx.TimeoutException:
    print("RESULT: The full guidance request timed out; the short AMD test can still succeed.")
except httpx.HTTPError as exc:
    print("RESULT: Network/HTTP failure:", type(exc).__name__, str(exc)[:800])
except Exception as exc:
    print("RESULT: Unexpected diagnostic failure:", type(exc).__name__, str(exc)[:800])
