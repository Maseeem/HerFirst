"""Focused tests for task-guidance quality and honest source labelling.

AMD is mocked here, so these tests never need real credentials or network.
Live AMD behaviour must be checked manually with the real backend/.env.
"""
from fastapi.testclient import TestClient

from app import services
from app.main import app

client = TestClient(app)

POCKETPANTRY = {
    "project": {
        "title": "PocketPantry",
        "description": "A simple app that helps people track the ingredients in their kitchen and see what expires soon.",
        "category": "web",
    },
    "task": {
        "id": "t-1-1",
        "milestone_id": "m-1",
        "title": "Clarify the single primary user action",
        "description": "Write down exactly what one primary action a person will take in PocketPantry.",
        "why_it_matters": "Beginning with a singular clear focus prevents overwhelm and scope creep.",
        "step_by_step_tips": ["List the minimal data required for that action"],
        "estimated_minutes": 20,
        "is_completed": False,
    },
}

GOOD_AMD_REPLY = {
    "task_id": "ignored",
    "task_title": "ignored",
    "summary": "You will have one sentence describing the first thing a person can do.",
    "what_to_do_next": "Open a notes app and write 'Primary action: PocketPantry'.",
    "why_it_matters": "A single clear action keeps the first version small.",
    "action_steps": [
        "1. Open a notes app.",
        "Step 2: Write the action sentence.",
        "3) List the information needed.",
        "Describe the first screen.",
    ],
    "common_pitfalls": ["Choosing two actions at once."],
    "beginner_encouragement": "Planning is real progress.",
    "realistic_example": "Add one ingredient: name 'Milk', expiry date 2026-11-02.",
    "expected_result": "Five lines of notes and a 'Done when' line.",
    "verification_steps": ["Read the sentence aloud; it has one verb."],
}


def _use_amd(monkeypatch, reply, error=None, model="test-model"):
    monkeypatch.setattr(services, "AMD_CONFIGURED", True)
    monkeypatch.setattr(services, "_amd_json", lambda prompt, payload: (reply, model if reply else None, error))


def test_amd_guidance_is_returned_and_labelled_amd(monkeypatch):
    seen = {}

    def fake(prompt, payload):
        seen["prompt"], seen["payload"] = prompt, payload
        return dict(GOOD_AMD_REPLY), "test-model", None

    monkeypatch.setattr(services, "AMD_CONFIGURED", True)
    monkeypatch.setattr(services, "_amd_json", fake)
    body = client.post("/api/tasks/guidance", json=POCKETPANTRY).json()
    assert body["source"] == "amd_ai"
    assert body["source_status"] == "Generated by AMD model test-model."
    assert body["task_id"] == "t-1-1"
    assert body["task_title"] == "Clarify the single primary user action"
    # Step numbers are stripped because the UI numbers the list itself.
    assert body["action_steps"][0] == "Open a notes app."
    assert body["action_steps"][2] == "List the information needed."
    # The model receives the real task, project, and hints.
    assert seen["payload"]["task"]["estimated_minutes"] == 20
    assert seen["payload"]["project"]["title"] == "PocketPantry"
    assert seen["payload"]["guide_hints"]["task_kind"] == "planning"
    assert "index.html" in seen["prompt"]


def test_thin_amd_reply_falls_back_and_is_not_labelled_amd(monkeypatch):
    thin = dict(GOOD_AMD_REPLY, action_steps=["Only one step."])
    _use_amd(monkeypatch, thin)
    body = client.post("/api/tasks/guidance", json=POCKETPANTRY).json()
    assert body["source"] == "domain_synthesizer"
    assert "fewer than 3" in body["source_status"]


def test_amd_failure_uses_offline_guide_with_reason(monkeypatch):
    _use_amd(monkeypatch, None, error="AMD model 'x' timed out after 45 seconds.")
    body = client.post("/api/tasks/guidance", json=POCKETPANTRY).json()
    assert body["source"] == "domain_synthesizer"
    assert "timed out" in body["source_status"]


def test_unconfigured_amd_never_claims_amd(monkeypatch):
    monkeypatch.setattr(services, "AMD_CONFIGURED", False)
    monkeypatch.setattr(services, "_amd_json", lambda prompt, payload: (None, None, "not configured"))
    body = client.post("/api/tasks/guidance", json=POCKETPANTRY).json()
    assert body["source"] == "domain_synthesizer"


def test_offline_pocketpantry_primary_action_guide_is_concrete(monkeypatch):
    monkeypatch.setattr(services, "AMD_CONFIGURED", False)
    monkeypatch.setattr(services, "_amd_json", lambda prompt, payload: (None, None, "offline"))
    body = client.post("/api/tasks/guidance", json=POCKETPANTRY).json()
    text = " ".join(body["action_steps"] + [body["realistic_example"], body["expected_result"]]).lower()
    assert "ingredient" in text and "expiry date" in text
    assert "done when" in text
    assert "no code" in body["what_to_do_next"].lower() or "no code" in body["expected_result"].lower()
    assert "index.html" not in text.replace("standalone index.html", "")
    assert len(body["action_steps"]) >= 6
    assert len(body["verification_steps"]) >= 3
    assert len(body["common_pitfalls"]) >= 3


def test_setup_and_planning_tasks_are_not_given_form_instructions(monkeypatch):
    monkeypatch.setattr(services, "AMD_CONFIGURED", False)
    monkeypatch.setattr(services, "_amd_json", lambda prompt, payload: (None, None, "offline"))
    inventory = {
        "title": "Pepsi Factory Inventory Management System",
        "description": "Warehouse stock, bottles, cartons and raw materials",
        "category": "web",
    }
    planning = {
        "id": "p1", "milestone_id": "m", "title": "Define product catalog and unit standards",
        "description": "Map out product lines.", "why_it_matters": "", "step_by_step_tips": ["List primary products"],
        "estimated_minutes": 25, "is_completed": False,
    }
    body = client.post("/api/tasks/guidance", json={"project": inventory, "task": planning}).json()
    assert any("List primary products" in step for step in body["action_steps"])
    assert "no code" in body["expected_result"].lower() or "notes" in body["expected_result"].lower()


def test_json_in_markdown_fence_is_parsed():
    assert services._parse_json_content('```json\n{"a": 1}\n```') == {"a": 1}
    assert services._parse_json_content('Sure! {"a": 1} Hope that helps.') == {"a": 1}
